#!/bin/bash


#***********************************************************************
# function rm-on-exit() -> deleting temporary files on exit
#-----------------------------------------------------------------------
declare -a files_to_be_deleted

function rm-on-exit() {
	[[ $# -gt 0 ]] && files_to_be_deleted+=("$@")
}

function on-exit() {
	for file in "${files_to_be_deleted[@]:-}"; do
		[[ -f "$file" ]] && rm -r "$file"
	done
	files_to_be_deleted=()
}

trap on-exit EXIT INT TERM QUIT ABRT ERR

